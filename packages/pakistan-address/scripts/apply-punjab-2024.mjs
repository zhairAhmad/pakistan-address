// One-time merge of the Punjab Board of Revenue notification of 18 December 2024
// (data-sources/punjab-2024) into data/pakistan.json. After this, data/pakistan.json is edited
// directly (see CONTRIBUTING.md); re-running overwrites later edits.
//
//   node scripts/apply-punjab-2024.mjs
//
// The notification is an official schedule of every division, district and tehsil of Punjab
// ("in supersession of all previous notifications"), so for Punjab it replaces the older lists:
// tehsils are matched by name within each district, moved when the notification places them in
// another district, added when new, and removed when the notification does not list them.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const dataFile = path.join(here, '..', 'data', 'pakistan.json');
const notifFile = path.join(here, '..', 'data-sources', 'punjab-2024', 'punjab-notification-2024-12-18.json');
const reportFile = path.join(here, '..', 'data-sources', 'punjab-2024', 'apply-report.md');

const data = JSON.parse(fs.readFileSync(dataFile, 'utf8'));
const notif = JSON.parse(fs.readFileSync(notifFile, 'utf8'));
const report = [];
const log = (...lines) => report.push(...lines);

const slugAll = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const strip = (s) => s.toUpperCase().replace(/\(.*?\)/g, ' ').replace(/[^A-Z0-9]+/g, '');
function lev(a, b) {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) dp[0][j] = j;
  for (let i = 1; i <= a.length; i++)
    for (let j = 1; j <= b.length; j++)
      dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return dp[a.length][b.length];
}
function score(a, b) {
  if (a === b) return 0;
  const d = lev(a, b);
  if (d <= Math.min(3, Math.floor(Math.min(a.length, b.length) / 4))) return d;
  const [s, l] = a.length <= b.length ? [a, b] : [b, a];
  if (s.length >= 5 && l.includes(s)) return 10 + l.length - s.length;
  return Infinity;
}
function match(as, bs, exactOnly = false) {
  const pairs = [];
  as.forEach((a, i) => bs.forEach((b, j) => {
    let best = Infinity;
    for (const x of a.keys) for (const y of b.keys) best = Math.min(best, score(x, y));
    if (best < Infinity && (!exactOnly || best === 0)) pairs.push({ i, j, d: best });
  }));
  pairs.sort((p, q) => p.d - q.d);
  const ua = new Set(), ub = new Set(), out = [];
  for (const p of pairs) { if (ua.has(p.i) || ub.has(p.j)) continue; ua.add(p.i); ub.add(p.j); out.push(p); }
  return out;
}
const keysOf = (r) => [r.name, ...(r.altNames ?? [])].map(strip);
const addAlt = (rec, name) => {
  const have = new Set([rec.name, ...(rec.altNames ?? [])].map(strip));
  if (!have.has(strip(name))) rec.altNames = [...(rec.altNames ?? []), name];
};

// ---------- check the transcription against the stated totals ----------
const nDiv = notif.divisions.length;
const nDist = notif.divisions.reduce((a, v) => a + v.districts.length, 0);
const nTeh = notif.divisions.reduce((a, v) => a + v.districts.reduce((b, d) => b + d.tehsils.length, 0), 0);
if (nDiv !== 10 || nDist !== 41 || nTeh !== 156) throw new Error(`transcription totals ${nDiv}/${nDist}/${nTeh}, expected 10/41/156`);
const dupes = notif.divisions.flatMap((v) => v.districts.flatMap((d) => d.tehsils.map((t) => d.name + '|' + t)));
if (new Set(dupes).size !== dupes.length) throw new Error('duplicate tehsil in transcription');

log('# Punjab notification merge report', '', `Generated by \`scripts/apply-punjab-2024.mjs\`. Source: ${notif.document.number}, ${notif.document.date}.`, '');

// ---------- divisions and districts ----------
const pbDiv = (name) => data.divisions.find((d) => d.provinceId === 'pb' && strip(d.name) === strip(name));
const pbDist = (name) => data.districts.find((d) => d.provinceId === 'pb' && strip(d.name) === strip(name));
log('## Districts and divisions', '');
const districts = []; // { notifDistrict, ours, id }
for (const v of notif.divisions) {
  const div = pbDiv(v.name);
  if (!div) throw new Error('no division ' + v.name);
  for (const nd of v.districts) {
    let d = pbDist(nd.name);
    if (!d) {
      d = { id: `pb-${slugAll(nd.name)}`, provinceId: 'pb', divisionId: div.id, name: nd.name };
      data.districts.push(d);
      log(`- Added district **${nd.name}** (\`${d.id}\`) in ${v.name} division.`);
    } else if (d.divisionId !== div.id) {
      log(`- District **${d.name}** moved to ${v.name} division.`);
      d.divisionId = div.id;
    }
    districts.push({ nd, d });
  }
}
const extraDistricts = data.districts.filter((d) => d.provinceId === 'pb' && !districts.some((x) => x.d === d));
if (extraDistricts.length) throw new Error('districts not in the notification: ' + extraDistricts.map((d) => d.name));
const taunsa = pbDist('Taunsa');
addAlt(taunsa, 'Taunsa Sharif');

// ---------- tehsils ----------
const punjabDistrictIds = new Set(districts.map((x) => x.d.id));
const ours = data.tehsils.filter((t) => punjabDistrictIds.has(t.districtId));
const used = new Set();
const unmatched = []; // notification tehsils not matched within their district
const changes = { kept: 0, renamed: 0, moved: 0, added: 0, removed: 0 };
const notes = [];

const claim = (t, nd, nt) => { // t: our record matched to notification tehsil nt of district nd
  used.add(t);
  if (strip(t.name) !== strip(nt)) { const old = t.name; t.name = nt; addAlt(t, old); changes.renamed++; notes.push(`- ${nd.d.name}: "${old}" is now "${nt}" (the old spelling is an alternate name)`); }
  else t.name = nt;
  t.altNames = (t.altNames ?? []).filter((a) => strip(a) !== strip(t.name));
  if (!t.altNames.length) delete t.altNames;
};

for (const { nd, d } of districts) {
  const pool = ours.filter((t) => t.districtId === d.id && !used.has(t));
  const m = match(nd.tehsils.map((n) => ({ keys: [strip(n)] })), pool.map((t) => ({ keys: keysOf(t) })));
  const matchedI = new Set(m.map((p) => p.i));
  for (const p of m) { claim(pool[p.j], { d }, nd.tehsils[p.i]); changes.kept++; }
  nd.tehsils.forEach((n, i) => { if (!matchedI.has(i)) unmatched.push({ d, n }); });
}
// moved: exact name elsewhere in Punjab
const remaining = ours.filter((t) => !used.has(t));
const mv = match(unmatched.map((u) => ({ keys: [strip(u.n)] })), remaining.map((t) => ({ keys: keysOf(t) })), true);
const movedI = new Set();
for (const p of mv) {
  const t = remaining[p.j], u = unmatched[p.i];
  const from = data.districts.find((x) => x.id === t.districtId);
  t.districtId = u.d.id; claim(t, { d: u.d }, u.n); changes.moved++; movedI.add(p.i);
  log(`- Moved tehsil **${u.n}** from ${from.name} to ${u.d.name}.`);
}
// added
unmatched.forEach((u, i) => {
  if (movedI.has(i)) return;
  data.tehsils.push({ id: '', districtId: u.d.id, name: u.n }); changes.added++;
  log(`- Added tehsil **${u.n}** to ${u.d.name}.`);
});
// removed
for (const t of ours.filter((x) => !used.has(x))) {
  const d = data.districts.find((x) => x.id === t.districtId);
  data.tehsils.splice(data.tehsils.indexOf(t), 1); changes.removed++;
  log(`- Removed tehsil **${t.name}** (${d.name}): not in the notification.`);
}
log('', '## Spelling changes', '', ...(notes.length ? notes : ['- none']));

// ---------- final checks ----------
const seen = new Set();
for (const t of data.tehsils) {
  let id = `${t.districtId}-${slugAll(t.name)}`;
  for (let n = 2; seen.has(id); n++) id = `${t.districtId}-${slugAll(t.name)}-${n}`;
  seen.add(id); t.id = id;
}
for (const { nd, d } of districts) {
  const have = data.tehsils.filter((t) => t.districtId === d.id).map((t) => strip(t.name)).sort().join();
  const want = nd.tehsils.map(strip).sort().join();
  if (have !== want) throw new Error(`tehsils of ${d.name} differ from the notification`);
}
data.meta.sources.push({
  name: `Government of the Punjab, Revenue Department, Notification ${notif.document.number}, ${notif.document.date}`,
  url: 'https://minutemirror.com.pk/wp-content/uploads/2024/12/Notification-of-Divisions-Districts-Tehsils-in-the-Punjab.pdf',
  license: 'Official government notification; only unit names are used',
  note: 'Divisions, districts and tehsils of Punjab (10 / 41 / 156), replacing the older Punjab lists. Scanned copy published by Minute Mirror; transcribed in data-sources/punjab-2024/',
});
data.meta.dataVersion = new Date().toISOString().slice(0, 10);
const ORDER = ['id', 'provinceId', 'divisionId', 'districtId', 'name', 'notice', 'altNames', 'pcode', 'pbsCode'];
const tidy = (r) => Object.fromEntries(ORDER.filter((k) => k in r).map((k) => [k, r[k]]));
const byName = (a, b) => a.name.localeCompare(b.name, 'en');
for (const k of ['districts', 'tehsils']) data[k] = data[k].map(tidy).sort(byName);

const pbTeh = data.tehsils.filter((t) => punjabDistrictIds.has(t.districtId)).length;
log('', '## Totals', '', `- tehsils kept (matched in their district): ${changes.kept}; moved between districts: ${changes.moved}; renamed to the notification spelling: ${changes.renamed}; added: ${changes.added}; removed: ${changes.removed}`,
  `- Punjab now: ${nDiv} divisions, ${punjabDistrictIds.size} districts, ${pbTeh} tehsils (the notification: 10 / 41 / 156)`);
if (pbTeh !== 156) throw new Error('Punjab tehsil total is ' + pbTeh);
fs.writeFileSync(dataFile, JSON.stringify(data, null, 1) + '\n');
fs.writeFileSync(reportFile, report.join('\n') + '\n');
console.log(report.slice(-3).join('\n'));
